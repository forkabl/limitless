#!/usr/bin/env python3

"""Generates a C++ header containing a small trusted WebUI resource set."""

from __future__ import annotations

import argparse
from pathlib import Path


def _cpp_string_literal(value: str) -> str:
    escaped = (
        value.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("\t", "\\t")
        .replace("\r", "\\r")
        .replace("\n", '\\n"\n    "')
    )
    return f'"{escaped}"'


def _parse_resource(value: str) -> tuple[str, Path]:
    name, separator, path = value.partition("=")
    if not separator or not name or not path:
        raise argparse.ArgumentTypeError(
            "resources must use the form SymbolName=/path/to/input"
        )
    if not name.isidentifier():
        raise argparse.ArgumentTypeError(f"invalid C++ symbol name: {name}")
    return name, Path(path)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", required=True, type=Path)
    parser.add_argument(
        "--resource", action="append", required=True, type=_parse_resource
    )
    args = parser.parse_args()

    declarations = []
    for name, path in args.resource:
        content = path.read_text(encoding="utf-8")
        declarations.append(
            f"inline constexpr std::string_view {name} =\n"
            f"    {_cpp_string_literal(content)};"
        )

    output = "\n".join(
        [
            "// Generated by embed_webui_resources.py. Do not edit.",
            "#ifndef LIMITLESS_SHELL_RESOURCES_LIMITLESS_SHELL_RESOURCES_H_",
            "#define LIMITLESS_SHELL_RESOURCES_LIMITLESS_SHELL_RESOURCES_H_",
            "",
            "#include <string_view>",
            "",
            "namespace limitless::resources {",
            "",
            "\n\n".join(declarations),
            "",
            "}  // namespace limitless::resources",
            "",
            "#endif  // LIMITLESS_SHELL_RESOURCES_LIMITLESS_SHELL_RESOURCES_H_",
            "",
        ]
    )

    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(output, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
